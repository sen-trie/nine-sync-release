# NineSync, combined extension. Registers NineSync: PMM Bridge and NineSync: FX Importer as namespaced
# components of this one package. Nothing is added to sys.path or sys.modules.
#
# mmd_tools is NOT part of this package: Core uses the user's separately installed mmd_tools extension and
# reports in its panel when it is missing, disabled or too old. This module never registers, unregisters or
# inspects mmd_tools, so enabling or disabling NineSync cannot affect it.
#
# Unsupported: running this next to standalone NineSync Core / FX. The entry point detects their
# registrations before it registers anything and refuses to start (fail closed); it never disables
# or changes another add-on.

BUNDLE_VERSION = (0, 3, 0)

# This package registers the one AddonPreferences class (Core's and FX's settings together, see preferences.py);
# the components see this marker on their parent package and register none of their own.
NINESYNC_PREFERENCES_OWNER = True

# FX reads its root package's bl_info["version"] (here: this package). Blender drops the attribute from an
# enabled extension's module, so it is set again at register time.
BL_INFO = {
    "name": "NineSync",
    "author": "sentrie",
    "version": BUNDLE_VERSION,
    "blender": (5, 3, 0),
    "category": "Import-Export",
}

import importlib

import bpy

from . import translations  # Release-owned UI strings; generated by packaging/i18n_tool.py

COMPONENTS = ("ninesync_core", "ninesync_fx")

_state = {"registered": [], "preferences": False}


def foreign_registrations():
    found = []
    if hasattr(bpy.types.Scene, "mmd_bridge"):
        found.append("NineSync: PMM Bridge")
    if hasattr(bpy.types.Scene, "ninesync_fx"):
        found.append("NineSync: FX Importer")
    registry = bpy.app.driver_namespace.get("ninesync_hooks") or {}
    if registry.get("core") is not None and "NineSync: PMM Bridge" not in found:
        found.append("NineSync hook registry (Core)")
    if "ninesync_fx" in (registry.get("post_sync") or {}) and "NineSync: FX Importer" not in found:
        found.append("NineSync hook registry (FX)")
    return found


def register():
    global bl_info
    bl_info = dict(BL_INFO)
    if _state["registered"]:
        return
    translations.register(__package__)
    found = foreign_registrations()
    if found:
        # The format string is translated, then filled in (a formatted message would never match the catalog).
        message = bpy.app.translations.pgettext_rpt(
            "NineSync (combined) cannot start: %s already registered from another install. "
            "Disable that install, then enable this one; restarting Blender is recommended. Nothing was changed."
        ) % ", ".join(found)
        translations.unregister(__package__)
        raise RuntimeError(message)
    done = []
    try:
        preferences = importlib.import_module(".preferences", __package__)
        preferences.register()
        _state["preferences"] = True
        for name in COMPONENTS:
            module = importlib.import_module("." + name, __package__)
            module.register()
            done.append(module)
    except Exception:
        for module in reversed(done):
            try:
                module.unregister()
            except Exception:
                pass
        release_preferences()
        translations.unregister(__package__)
        raise
    _state["registered"] = done


def release_preferences():
    if not _state["preferences"]:
        return
    _state["preferences"] = False
    try:
        importlib.import_module(".preferences", __package__).unregister()
    except Exception as error:
        print("NineSync: unregister of the preferences failed: %r" % (error,))


def unregister():
    done, _state["registered"] = _state["registered"], []
    for module in reversed(done):
        try:
            module.unregister()
        except Exception as error:
            print("NineSync: unregister of %s failed: %r" % (module.__name__, error))
    release_preferences()
    translations.unregister(__package__)


# FX's relink operator calls this on its root package (its ADDON_PACKAGE is this extension).
def reload_in_place():
    unregister()
    register()
